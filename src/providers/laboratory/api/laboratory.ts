/* =========================================================
   CHECK ROUTE NOT FOUND
========================================================= */

function isRouteNotFound(error: any) {
  const message = String(error?.message || "").toLowerCase();

  return error?.status === 404 && message.includes("route not found");
}

/* =========================================================
   LEGACY PROVIDER CONTEXT
========================================================= */

async function getLegacyProviderContext() {
  const providerUserId = getLaboratoryProviderUserId();

  console.log("");
  console.log("==========================================");
  console.log("LEGACY PROVIDER CONTEXT");
  console.log("==========================================");

  console.log("Provider User ID:", providerUserId || "MISSING");

  const [labsResponse, scanResponse] = await Promise.all([
    getLabs(),
    getScanCenters(),
  ]);

  const labs = Array.isArray(labsResponse?.data) ? labsResponse.data : [];

  const scanCenters = Array.isArray(scanResponse?.data)
    ? scanResponse.data
    : [];

  const lab =
    labs.find((item: any) => item.labUserId === providerUserId) || null;

  const scanCenter =
    scanCenters.find((item: any) => item.scanCenterUserId === providerUserId) ||
    null;

  console.log("Labs count:", labs.length);

  console.log("Scan centers count:", scanCenters.length);

  console.log("Matched Lab:", lab);

  console.log("Matched Scan Center:", scanCenter);

  console.log("==========================================");

  return {
    providerUserId,
    lab,
    scanCenter,
    labs,
    scanCenters,
  };
}

/* =========================================================
   PROVIDER CONTEXT
========================================================= */

export async function getProviderContext() {
  console.log("");
  console.log("==========================================");
  console.log("GET PROVIDER CONTEXT");
  console.log("==========================================");

  const providerUserId = getLaboratoryProviderUserId();

  console.log("Provider User ID:", providerUserId || "MISSING");

  try {
    const response = await getLabScanUser();

    console.log("LABSCAN USER RESPONSE:", response);

    const data = response?.data || {};

    const labs = Array.isArray(data.labs) ? data.labs : [];

    const scanCenters = Array.isArray(data.scanCenters) ? data.scanCenters : [];

    const lab =
      labs.find((item: any) => item.labUserId === providerUserId) ||
      labs[0] ||
      null;

    const scanCenter =
      scanCenters.find(
        (item: any) => item.scanCenterUserId === providerUserId,
      ) ||
      scanCenters[0] ||
      null;

    console.log("");
    console.log("Labs:", labs);

    console.log("Scan Centers:", scanCenters);

    console.log("Selected Lab:", lab);

    console.log("Selected Lab ID:", lab?.labId || "MISSING");

    console.log("Selected Scan Center:", scanCenter);

    console.log(
      "Selected Scan Center ID:",
      scanCenter?.scanCenterId || "MISSING",
    );

    console.log("==========================================");

    return {
      providerUserId,
      lab,
      scanCenter,
      labs,
      scanCenters,
    };
  } catch (error) {
    console.log("");
    console.log("==========================================");
    console.log("PROVIDER CONTEXT ERROR");
    console.log("==========================================");
    console.log("Error:", error);
    console.log("Status:", (error as any)?.status);
    console.log("Data:", (error as any)?.data);
    console.log("==========================================");

    /*
      If /user does not exist on an older backend,
      use the existing lab/scan center APIs.
    */

    if (isRouteNotFound(error)) {
      console.log("LabScan /user route not found.");

      console.log("Using legacy provider context.");

      return getLegacyProviderContext();
    }

    throw error;
  }
}

/* =========================================================
   PROVIDER REGISTRATION STATUS
========================================================= */

export async function getProviderRegistrationStatus() {
  console.log("");
  console.log("==========================================");
  console.log("CHECK PROVIDER REGISTRATION");
  console.log("==========================================");

  try {
    const context = await getProviderContext();

    const registered = Boolean(context.lab || context.scanCenter);

    console.log("Registered:", registered);

    console.log("Lab ID:", context.lab?.labId || "MISSING");

    console.log(
      "Scan Center ID:",
      context.scanCenter?.scanCenterId || "MISSING",
    );

    console.log("==========================================");

    return {
      registered,
      context,
    };
  } catch (error: any) {
    console.log("Registration check error:", error);

    /*
      A normal 404 can mean that the provider
      does not have a Lab/Scan profile.
    */

    if (error?.status === 404 && !isRouteNotFound(error)) {
      console.log("Provider is not registered.");

      return {
        registered: false,
        context: null,
      };
    }

    throw error;
  }
}

/* =========================================================
   FILTER PROVIDER APPOINTMENTS
========================================================= */

export function filterProviderAppointments(
  appointments: Appointment[],
  labId?: string,
  scanCenterId?: string,
) {
  console.log("");
  console.log("==========================================");
  console.log("FILTER PROVIDER APPOINTMENTS");
  console.log("==========================================");

  console.log("Total appointments:", appointments.length);

  console.log("Lab ID:", labId || "MISSING");

  console.log("Scan Center ID:", scanCenterId || "MISSING");

  const filtered = appointments.filter((appointment) => {
    const appointmentLabId =
      appointment.labId || appointment.lab?.labId || null;

    const appointmentScanCenterId =
      appointment.scanCenterId || appointment.scanCenter?.scanCenterId || null;

    return Boolean(
      (labId && appointmentLabId === labId) ||
      (scanCenterId && appointmentScanCenterId === scanCenterId),
    );
  });

  console.log("Filtered appointments:", filtered.length);

  console.log("==========================================");

  return filtered;
}

/* =========================================================
   PROVIDER APPOINTMENTS
========================================================= */

export async function getProviderAppointments() {
  console.log("");
  console.log("==========================================");
  console.log("GET PROVIDER APPOINTMENTS");
  console.log("==========================================");

  const context = await getProviderContext();

  console.log("Provider context:", context);

  /* -------------------------------------------------------
     LAB PROVIDER
  ------------------------------------------------------- */

  if (context.lab?.labId) {
    console.log("Provider type: LAB");

    console.log("Lab ID:", context.lab.labId);

    console.log("Calling lab appointment API...");

    try {
      const response = await getLabAppointmentsByLabId(context.lab.labId);

      console.log("");
      console.log("==========================================");
      console.log("LAB APPOINTMENT RESPONSE");
      console.log("==========================================");

      console.log("Response:", response);

      console.log(
        "Appointment count:",
        Array.isArray(response?.data) ? response.data.length : 0,
      );

      console.log("==========================================");

      return {
        response,
        context,
      };
    } catch (error) {
      console.log("");
      console.log("==========================================");
      console.log("LAB APPOINTMENTS ERROR");
      console.log("==========================================");

      console.log("Error:", error);

      console.log("Status:", (error as any)?.status);

      console.log("Data:", (error as any)?.data);

      console.log("Lab ID:", context.lab.labId);

      console.log("==========================================");

      throw error;
    }
  }

  /* -------------------------------------------------------
     SCAN CENTER PROVIDER
  ------------------------------------------------------- */

  console.log("Provider type: SCAN");

  console.log("Scan Center ID:", context.scanCenter?.scanCenterId || "MISSING");

  const response = await getScanAppointments();

  const allAppointments = Array.isArray(response?.data) ? response.data : [];

  const filtered = allAppointments.filter((appointment: Appointment) => {
    const appointmentScanCenterId =
      appointment.scanCenterId || appointment.scanCenter?.scanCenterId || null;

    return appointmentScanCenterId === context.scanCenter?.scanCenterId;
  });

  console.log("All scan appointments:", allAppointments.length);

  console.log("Filtered scan appointments:", filtered.length);

  console.log("==========================================");

  return {
    response: {
      ...response,
      data: filtered,
    },
    context,
  };
}

