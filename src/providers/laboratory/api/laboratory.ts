/* =========================================================
   CREATE LAB APPOINTMENT
   bookingId is generated by the backend; do not send it.
========================================================= */

export type CreateLabAppointmentPayload = {
  patientId: string;
  labId: string;
  appointmentType: "LAB";
  appointmentMode: "HOME" | "CENTER";
  appointmentDate: string;
  startTime: string;
  endTime: string;
  address?: string;
  patientNotes?: string;
  tests: Array<{ labTestId: string }>;
};

export function createLabAppointment(payload: CreateLabAppointmentPayload) {
  return laboratoryApi("/appointment", {
    method: "POST",
    body: JSON.stringify({
      patientId: payload.patientId,
      labId: payload.labId,
      appointmentType: payload.appointmentType,
      appointmentMode: payload.appointmentMode,
      appointmentDate: payload.appointmentDate,
      startTime: payload.startTime,
      endTime: payload.endTime,
      ...(payload.address ? { address: payload.address } : {}),
      ...(payload.patientNotes ? { patientNotes: payload.patientNotes } : {}),
      tests: payload.tests,
    }),
  });
}

